def reaction_action_sql(m: dict[str, Any], r: dict[str, Any]) -> str:
    ent = M.event_entity(m, r["on"])
    kind = r["do"]
    if kind == "set":
        assigns = []
        for fk, val in r["set"].items():
            f = ent["fields"][fk]
            if isinstance(val, str) and val.startswith("="):
                expr = {"=now": "now()", "=today": "current_date", "=actor": "new.actor_id", "=null": "null"}[val]
            else:
                expr = literal(m, f, val)
            assigns.append(f"{fk} = {expr}")
        return (f"perform set_config('app.system', 'on', true);\n"
                f"      update public.{ent['table']} set {', '.join(assigns)} where id = new.entity_id;\n"
                f"      perform set_config('app.system', 'off', true);")
    if kind == "transition":
        tr = ent["workflow"]["transitions"][r["transition"]]
        return (f"if exists (select 1 from public.{ent['table']} x where x.id = new.entity_id and x.state = any ({arr(tr['from'])})) then\n"
                f"        begin\n"
                f"          perform public.{ent['snake']}_perform_transition(new.entity_id, {q(r['transition'])}, null, true);\n"
                f"        exception when others then\n"
                f"          raise warning 'reaction {r['name']} skipped: %', sqlerrm;\n"
                f"        end;\n      end if;")
    if kind == "schedule":
        fld, off = M.parse_offset(str(r["at"]))
        return (f"insert into public.scheduled_events (reaction, type, entity, entity_id, fire_at)\n"
                f"      select {q(r['name'])}, {q(r['event'])}, {q(ent['snake'])}, x.id, (x.{fld}{off})::timestamptz\n"
                f"        from public.{ent['table']} x where x.id = new.entity_id and x.{fld} is not null\n"
                f"      on conflict (reaction, entity_id) do update set fire_at = excluded.fire_at, fired_at = null, last_error = null;")
    if kind == "broadcast":
        return (f"perform public.broadcast({q(r['channel'])}, new.type, jsonb_build_object('type', new.type, 'subject', new.subject,\n"
                f"        'entity', new.entity, 'entity_id', new.entity_id, 'occurred_at', new.occurred_at));")
    if kind == "custom":
        return f"perform public.custom_{r['handler']}(new);"
    return "null;"


def reactions_sql(m: dict[str, Any]) -> str:
    by_event: dict[str, list[dict[str, Any]]] = {}
    for r in m["reactions"]:
        if r.get("do") in ("notify",):
            continue
        by_event.setdefault(r["on"], []).append(r)
    blocks = []
    declares = []
    for ev, rs in by_event.items():
        ent = M.event_entity(m, ev)
        inner = []
        needs_row = any(r["when"].get("clauses") for r in rs)
        if needs_row and ent:
            declares.append(f"  r_{ent['snake']} public.{ent['table']};")
            inner.append(f"    select * into r_{ent['snake']} from public.{ent['table']} where id = new.entity_id;")
        for r in rs:
            cond = when_sql(m, ent, r, extra="new.data", row=f"r_{ent['snake']}" if ent else "r")
            inner.append(f"    -- {r['name']} ({r['do']})\n    if {cond} then\n      {reaction_action_sql(m, r)}\n    end if;")
        blocks.append(f"  if new.type = {q(ev)} then\n" + "\n".join(inner) + "\n  end if;")
    body = "\n".join(blocks) if blocks else "  -- no internal reaction in the model"
    declares_sql = "\n".join(sorted(set(declares)))
    stubs = []
    for r in m["reactions"]:
        if r.get("do") == "custom":
            h = r["handler"]
            stubs.append(f"""do $do$
begin
  if to_regprocedure('public.custom_{h}(public.events)') is null then
    -- Stub created once by appforge; implement it in a hand-written migration (create or replace).
    create function public.custom_{h}(p_event public.events)
    returns void
    language plpgsql
    security definer
    set search_path = ''
    as $fn$
    begin
      raise notice 'custom handler {h} not implemented yet (event %)', p_event.type;
    end;
    $fn$;
    revoke execute on function public.custom_{h}(public.events) from public, anon, authenticated;
  end if;
end;
$do$;
""")
    return "\n".join(stubs) + f"""
-- Internal reactions (set, transition, schedule, broadcast, custom): run in the
-- producer's transaction, right after the event is written to the outbox.
create or replace function public.react_to_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
{declares_sql}
begin
  if pg_trigger_depth() > 12 then
    raise exception 'Troppe reazioni annidate (ciclo di reazioni?) sull''evento %', new.type;
  end if;
{body}
  return null;
end;
$$;

drop trigger if exists events_react on public.events;
create trigger events_react after insert on public.events
  for each row execute function public.react_to_event();
"""


def event_types_sql(m: dict[str, Any]) -> str:
    rows = []
    for t, ev in sorted(M.all_events(m).items()):
        ent = m["entities"].get(ev.get("entity") or "")
        rows.append(f"  ({q(t)}, {q(ev['category'])}, {q(ev['description'])}, {q(ent['snake']) if ent else 'null'})")
    return ("insert into public.event_types (type, category, description, entity) values\n" + ",\n".join(rows) +
            "\non conflict (type) do update set category = excluded.category, description = excluded.description, entity = excluded.entity;\n")


def grants_sql(m: dict[str, Any]) -> str:
    rpc = ["public.current_profile_id()", "public.has_role(public.app_role, uuid)", "public.is_admin()",
           "public.app_setting(text)", "public.role_is_scoped(public.app_role)",
           "public.perform_transition(text, uuid, text, text)", "public.available_transitions(text, uuid)",
           "public.my_inbox()", "public.record_history_of(text, uuid)", "public.can(text, text, uuid)", "public.approve_user(uuid, public.app_role, uuid[])",
           "public.set_my_locale(text)", "public.redeliver_webhook(uuid)", "public.replay_event(uuid, uuid)",
           "public.send_test_webhook(uuid)", "public.rotate_webhook_secret(uuid)", "public.clear_previous_webhook_secret(uuid)",
           "public.generate_webhook_secret()", "public.event_type_matches(text, text)"]
    for e in m["entities"].values():
        rpc.append(f"public.{e['snake']}_can(text, public.{e['table']})")
        rpc.append(f"public.{e['snake']}_principals(public.{e['table']})")
    rpc_list = ",\n  ".join(rpc)
    return f"""-- Functions are private unless listed here (each checks permissions itself).
revoke execute on all functions in schema public from public, anon, authenticated;
grant execute on function
  {rpc_list}
to authenticated;
grant execute on function public.before_user_created_hook(jsonb) to supabase_auth_admin;
"""


def cron_sql() -> str:
    return """do $cron$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('appforge-scheduled-events', '*/5 * * * *', 'select public.fire_due_scheduled_events()');
    perform cron.schedule('appforge-timed-transitions', '0 1 * * *', 'select public.run_timed_transitions()');
    perform cron.schedule('appforge-state-reminders', '0 7 * * *', 'select public.run_state_reminders()');
    perform cron.schedule('appforge-purge-events', '30 3 * * *', 'select public.purge_old_events()');
  end if;
end;
$cron$;
"""


def behavior_sql(m: dict[str, Any]) -> str:
    out = [HEADER, """-- =============================================================================
-- Domain behaviour: permissions (RLS), lifecycle triggers, event payloads,
-- workflow engine, reactions, scheduled jobs. Idempotent: regenerated in full
-- at every generation.
-- =============================================================================

"""]
    out.append(roles_sql(m) + "\n")
    out.append(event_types_sql(m) + "\n")
    # functions first (some reference each other at run time only)
    for e in m["entities"].values():
        out.append(f"-- ===================== {e['name']} =====================\n")
        out.append(principals_fn(m, e) + "\n" + can_fn(m, e) + "\n")
        if e["workflow"]:
            out.append(state_json_fn(m, e) + "\n" + state_check_sql(e) + "\n")
        out.append(json_fn(m, e) + "\n" + resolve_recipients_fn(m, e) + "\n" + recipients_for_fn(m, e) + "\n")
        out.append(emit_fn(m, e) + "\n" + lifecycle_fns(m, e) + "\n")
        if e["workflow"]:
            out.append(transition_fns(m, e) + "\n")
        out.append(policies_sql(m, e) + "\n")
    out.append("-- ===================== Engine =====================\n")
    out.append(system_recipients_fn(m) + "\n" + dispatch_fns(m) + "\n" + timed_sql(m) + "\n" + reminders_sql(m) + "\n")
    out.append(reactions_sql(m) + "\n")
    out.append(grants_sql(m) + "\n" + cron_sql())
    return "".join(out)
