"""SQL generation: core, structure and behaviour layers.

Three layers, with different evolution rules:

* core       generated once (first migration): users, roles, auth hooks, the
             transactional outbox, webhooks, scheduling tables. Later changes
             to it are hand-written migrations.
* structure  tables, columns, enums, foreign keys. Generated in full for a new
             app; for an evolving model only the *additive* delta is generated
             (see diff.py). Destructive changes are reported, never guessed.
* behaviour  functions, triggers, RLS policies, grants, event catalogue, cron.
             Idempotent (create or replace / drop ... if exists) and regenerated
             in full at every generation, so it always matches the model.
"""

