def display_expr(m: dict[str, Any], e: dict[str, Any], alias: str) -> str:
    d = e["display"]
    if d == "id":
        return f"{alias}.id::text"
    if d == "code":
        return f"{alias}.code"
    f = e["fields"].get(d)
    if f and f["type"] == "ref":
        return f"{alias}.{d}::text"
    return f"{alias}.{d}::text"


def ref_object(m: dict[str, Any], f: dict[str, Any], alias: str) -> str:
    if f["to"] == "User":
        return f"jsonb_build_object('id', {alias}.id, 'display', coalesce({alias}.full_name, {alias}.email), 'email', {alias}.email)"
    te = m["entities"][f["to"]]
    parts = [f"'id', {alias}.id", f"'display', {display_expr(m, te, alias)}"]
    if te["code_prefix"]:
        parts.append(f"'code', {alias}.code")
    em = M.email_field(m, f["to"])
    if em:
        parts.append(f"'email', {alias}.{em}")
    return f"jsonb_build_object({', '.join(parts)})"


def json_fn(m: dict[str, Any], e: dict[str, Any]) -> str:
    s, t = e["snake"], e["table"]
    pieces = [
        f"jsonb_build_object('id', r.id, 'entity', {q(s)}, 'display', {display_expr(m, e, 'r')}, "
        f"'url', trim(both '\"' from coalesce(public.app_setting('app_base_url')::text, '')) || '/e/{s}/' || r.id)",
    ]
    if e["code_prefix"]:
        pieces.append("jsonb_build_object('code', r.code)")
    for f in e["fields"].values():
        k = f["key"]
        if f["type"] == "ref" and f["many"]:
            target = M.ref_target_table(m, f["to"])
            jt = join_table_name(e, f)
            pieces.append(f"jsonb_build_object({q(k)}, coalesce((select jsonb_agg({ref_object(m, f, 'x')} order by j.position) "
                          f"from public.{jt} j join public.{target} x on x.id = j.target_id where j.record_id = r.id), '[]'::jsonb))")
        elif f["type"] == "ref":
            target = M.ref_target_table(m, f["to"])
            pieces.append(f"jsonb_build_object({q(k)}, (select {ref_object(m, f, 'x')} from public.{target} x where x.id = r.{k}))")
        elif f["type"] == "enum":
            en = m["enums"][f["enum"]]
            cases = " ".join(f"when {q(v['key'])} then {labels_json(v['label'])}" for v in en["values"])
            pieces.append(f"jsonb_build_object({q(k)}, case when r.{k} is null then null else "
                          f"jsonb_build_object('key', r.{k}, 'labels', case r.{k}::text {cases} end) end)")
        else:
            pieces.append(f"jsonb_build_object({q(k)}, r.{k})")
    if e["kind"] == "process":
        pieces.append(f"jsonb_build_object('state', public.{s}_state_json(r.state))")
    pieces.append("jsonb_build_object('created_by', public.actor_json(r.created_by), 'created_at', r.created_at, 'updated_at', r.updated_at)")
    body = "\n      || ".join(pieces)
    return f"""-- Event payload of a {e['name']}: scalar fields, references resolved to {{id, display[, email]}}.
create or replace function public.{s}_json(p_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select {body}
    from public.{t} r where r.id = p_id;
$$;
"""


def resolve_recipients_fn(m: dict[str, Any], e: dict[str, Any]) -> str:
    s, t = e["snake"], e["table"]
    loc = default_locale(m)
    scope = scope_expr(m, e)
    parts = [
        # roles
        f"""select p.email, p.locale, ur.role::text as kind
      from public.user_roles ur join public.profiles p on p.id = ur.profile_id
     where ur.role::text = any (p_principals) and p.active and p.approved_at is not null
       and (not public.role_is_scoped(ur.role) or {scope} is null or ur.scope_id = {scope})""",
        """select p.email, p.locale, 'creator' from public.profiles p
     where 'creator' = any (p_principals) and p.id = r.created_by and p.active""",
        f"""select substr(x, 7), {q(loc)}, 'email' from unnest(p_principals) x where x like 'email:%'""",
    ]
