def enum_sql(en: dict[str, Any]) -> str:
    vals = ", ".join(q(v["key"]) for v in en["values"])
    return f"create type public.{en['type']} as enum ({vals});\n"


def column_sql(m: dict[str, Any], e: dict[str, Any], f: dict[str, Any]) -> str:
    """Column definition (without foreign keys, added separately)."""
    parts = [f"{f['key']} {col_type(m, f)}"]
    if f["type"] == "bool":
        parts.append(f"not null default {literal(m, f, f['default'] if f['default'] is not None else False)}")
    else:
        if f["default"] is not None:
            parts.append(f"default {literal(m, f, f['default'])}")
        if f["required"]:
            parts.append("not null")
    if f["unique"]:
        parts.append("unique")
    checks = column_checks(e, f)
    if checks:
        parts.append(f"check ({' and '.join(checks)})")
    return " ".join(parts)


def column_checks(e: dict[str, Any], f: dict[str, Any]) -> list[str]:
    k, t = f["key"], f["type"]
    out = []
    if t == "string":
        out.append(f"char_length({k}) <= {int(f['max_length'] or 300)}")
    elif f["max_length"] and t in ("text", "url", "email"):
        out.append(f"char_length({k}) <= {int(f['max_length'])}")
    if t == "email":
        out.append(f"{k} ~ '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$' and {k} = lower({k})")
    if t == "url":
        out.append(f"{k} ~ '^https?://'")
    if f["min"] is not None:
        out.append(f"{k} >= {f['min']}")
    if f["max"] is not None and t in ("int", "number", "money"):
        out.append(f"{k} <= {f['max']}")
    if f["required"] and t in ("string", "text", "email", "url"):
        out.append(f"char_length(trim({k})) > 0")
    return out


def table_sql(m: dict[str, Any], e: dict[str, Any]) -> str:
    cols = ["id uuid primary key default gen_random_uuid()"]
    if e["code_prefix"]:
        cols.append("code text not null unique")
    for f in e["fields"].values():
        if f["many"]:
            continue
        cols.append(column_sql(m, e, f))
    if e["kind"] == "process":
        cols.append("state text not null")
    cols += [
        "created_by uuid",
        "created_at timestamptz not null default now()",
        "updated_at timestamptz not null default now()",
    ]
    body = ",\n  ".join(cols)
    out = f"-- {e['name']}: {e['label'][default_locale(m)]}\ncreate table public.{e['table']} (\n  {body}\n);\n"
    return out


def join_table_name(e: dict[str, Any], f: dict[str, Any]) -> str:
    return f"{e['table']}_{f['key']}"


def join_table_sql(m: dict[str, Any], e: dict[str, Any], f: dict[str, Any]) -> str:
    jt = join_table_name(e, f)
    target = M.ref_target_table(m, f["to"])
    return (f"create table public.{jt} (\n"
            f"  record_id uuid not null references public.{e['table']} (id) on delete cascade,\n"
            f"  target_id uuid not null references public.{target} (id) on delete cascade,\n"
            f"  position  int not null default 0,\n"
            f"  primary key (record_id, target_id)\n);\n"
            f"create index {jt}_target_idx on public.{jt} (target_id);\n")


def fk_sql(m: dict[str, Any], e: dict[str, Any], f: dict[str, Any]) -> str:
    target = M.ref_target_table(m, f["to"])
    action = {"cascade": "cascade", "restrict": "restrict", "set_null": "set null"}[f["on_delete"]]
    return (f"alter table public.{e['table']} add constraint {e['table']}_{f['key']}_fkey\n"
            f"  foreign key ({f['key']}) references public.{target} (id) on delete {action};\n"
            f"create index {e['table']}_{f['key']}_idx on public.{e['table']} ({f['key']});\n")


def entity_structure_sql(m: dict[str, Any], e: dict[str, Any], with_fks: bool = True) -> str:
    out = table_sql(m, e)
    out += (f"alter table public.{e['table']} add constraint {e['table']}_created_by_fkey\n"
            f"  foreign key (created_by) references public.profiles (id) on delete set null;\n")
    if e["kind"] == "process":
        out += f"create index {e['table']}_state_idx on public.{e['table']} (state);\n"
    for i, ix in enumerate(e["indexes"]):
        out += f"create index {e['table']}_ix{i + 1} on public.{e['table']} ({', '.join(ix)});\n"
    out += f"create trigger {e['table']}_updated_at before update on public.{e['table']}\n  for each row execute function public.set_updated_at();\n"
    return out


def entity_refs_sql(m: dict[str, Any], e: dict[str, Any]) -> str:
    out = ""
    for f in e["fields"].values():
        if f["type"] != "ref":
            continue
        out += join_table_sql(m, e, f) if f["many"] else fk_sql(m, e, f)
    return out


def structure_sql(m: dict[str, Any]) -> str:
    out = [HEADER, "-- =============================================================================\n"
           "-- Domain structure: enums, tables, references.\n"
           "-- =============================================================================\n\n"]
    for en in m["enums"].values():
        out.append(enum_sql(en))
    out.append("\n")
    for e in m["entities"].values():
        out.append(entity_structure_sql(m, e) + "\n")
    out.append("-- References (after every table exists: cycles are allowed)\n")
    for e in m["entities"].values():
        out.append(entity_refs_sql(m, e))
    sc = M.scope_entity(m)
    if sc:
        out.append(f"\n-- Scoped roles point to {sc['name']}\n"
                   f"alter table public.user_roles add constraint user_roles_scope_fkey\n"
                   f"  foreign key (scope_id) references public.{sc['table']} (id) on delete cascade;\n")
    return "".join(out)


