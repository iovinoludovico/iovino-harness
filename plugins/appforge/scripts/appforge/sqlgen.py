# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def q(value: Any) -> str:
    """SQL string literal."""
    return "'" + str(value).replace("'", "''") + "'"


def jq(value: Any) -> str:
    """jsonb literal."""
    return q(json.dumps(value, ensure_ascii=False, sort_keys=True)) + "::jsonb"


def arr(values: list[str]) -> str:
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def ident(name: str) -> str:
    return name  # identifiers are validated snake_case


def col_type(m: dict[str, Any], f: dict[str, Any]) -> str:
    t = f["type"]
    return {
        "string": "text", "text": "text", "email": "text", "url": "text", "int": "integer", "number": "numeric",
        "money": "numeric(14,2)", "bool": "boolean", "date": "date", "datetime": "timestamptz", "json": "jsonb",
        "ref": "uuid",
    }.get(t) or (f"public.{m['enums'][f['enum']]['type']}" if t == "enum" else "text")


def literal(m: dict[str, Any], f: dict[str, Any] | None, value: Any) -> str:
    """Typed SQL literal for a field value."""
    if value is None:
        return "null"
    if f is None:
        return q(value)
    t = f["type"]
    if t == "bool":
        return "true" if value in (True, "true", 1) else "false"
    if t in ("int", "number", "money"):
        return str(float(value) if t != "int" else int(value)).rstrip("0").rstrip(".") if t != "int" else str(int(value))
    if t == "enum":
        return f"{q(value)}::public.{m['enums'][f['enum']]['type']}"
    if t == "date":
        return f"{q(value)}::date"
    if t == "datetime":
        return f"{q(value)}::timestamptz"
    if t == "ref":
        return f"{q(value)}::uuid"
    if t == "json":
        return jq(value)
    return q(value)


def processes(m: dict[str, Any]) -> list[dict[str, Any]]:
    return [e for e in m["entities"].values() if e["kind"] == "process"]


def scope_expr(m: dict[str, Any], e: dict[str, Any], row: str = "r") -> str:
    """Expression giving the scope id of a row (null when the entity is not scoped)."""
    sc = M.scope_entity(m)
    if sc and sc["name"] == e["name"]:
        return f"{row}.id"
    if e["scope_field"]:
        return f"{row}.{e['scope_field']}"
    return "null::uuid"


def labels_json(labels: dict[str, str]) -> str:
    return jq(labels)


def default_locale(m: dict[str, Any]) -> str:
    return m["app"]["locales"][0]


# --------------------------------------------------------------------------- #
# Clauses (guards, conditions, reaction filters)
# --------------------------------------------------------------------------- #
def clause_sql(m: dict[str, Any], e: dict[str, Any], c: dict[str, Any], row: str = "r") -> str:
    key, op = c["field"], c["op"]
    f = e["fields"].get(key)
    col = f"{row}.{key}"
    textual = f is not None and f["type"] in ("string", "text", "email", "url")
    if op == "is_set":
        return f"nullif(trim({col}), '') is not null" if textual else f"{col} is not null"
    if op == "is_empty":
        return f"nullif(trim({col}), '') is null" if textual else f"{col} is null"
    if op == "is_true":
        return f"coalesce({col}, false)"
    if op == "is_false":
        return f"not coalesce({col}, false)"
    val = c.get("value")
    if key == "state":
        f = {"type": "string"}
    if op in ("in", "not_in"):
        items = ", ".join(literal(m, f, v) for v in val)
        expr = f"coalesce({col} = any(array[{items}]), false)"
        return expr if op == "in" else f"not {expr}"
    sym = {"eq": "=", "neq": "is distinct from", "gt": ">", "gte": ">=", "lt": "<", "lte": "<="}[op]
    if op == "eq":
        return f"coalesce({col} = {literal(m, f, val)}, false)"
    if op == "neq":
        return f"{col} is distinct from {literal(m, f, val)}"
    return f"coalesce({col} {sym} {literal(m, f, val)}, false)"


def clauses_sql(m: dict[str, Any], e: dict[str, Any], clauses: list[dict[str, Any]], row: str = "r") -> str:
    if not clauses:
        return "true"
    return " and ".join(f"({clause_sql(m, e, c, row)})" for c in clauses)


def unmet_sql(m: dict[str, Any], e: dict[str, Any], clauses: list[dict[str, Any]], row: str = "r") -> str:
    """jsonb array of the clauses that do not hold."""
    if not clauses:
        return "'[]'::jsonb"
    rows = ", ".join(f"(({clause_sql(m, e, c, row)}), {jq(c)})" for c in clauses)
    return f"(select coalesce(jsonb_agg(c.clause), '[]'::jsonb) from (values {rows}) c(ok, clause) where not coalesce(c.ok, false))"


