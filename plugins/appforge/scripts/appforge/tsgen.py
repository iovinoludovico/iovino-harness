def domain_md(m: dict[str, Any]) -> str:
    loc = m["app"]["locales"][0]
    L = []
    L.append(f"<!-- @generated by appforge from app.yaml. Do not edit. -->\n# {m['app']['name']}: modello di dominio\n")
    if m["app"]["description"]:
        L.append(m["app"]["description"] + "\n")
    L.append("## Ruoli\n\n| Ruolo | Etichetta | Ambito |\n|---|---|---|")
    sc = M.scope_entity(m)
    for k, r in m["roles"].items():
        L.append(f"| `{k}` | {r['label'][loc]} | {('per ' + sc['name']) if r['scoped'] and sc else 'globale'} |")
    L.append("")
    # ER diagram
    L.append("## Entità\n\n```mermaid\nerDiagram")
    for name, e in m["entities"].items():
        L.append(f"  {name} {{")
        if e["code_prefix"]:
            L.append("    text code")
        for f in e["fields"].values():
            if f["many"]:
                continue
            typ = f["enum"] if f["type"] == "enum" else f["type"]
            L.append(f"    {typ} {f['key']}{' FK' if f['type'] == 'ref' else ''}")
        if e["kind"] == "process":
            L.append("    text state")
        L.append("  }")
    for name, e in m["entities"].items():
        for f in e["fields"].values():
            if f["type"] != "ref":
                continue
            target = f["to"]
            card = "}o--o{" if f["many"] else ("}o--||" if f["required"] else "}o--o|")
            L.append(f"  {name} {card} {target} : {f['key']}")
    L.append("```\n")
    for name, e in m["entities"].items():
        L.append(f"### {name} — {e['label'][loc]} (`{e['table']}`, {e['kind']})\n")
        if e["description"]:
            L.append(e["description"] + "\n")
        L.append("| Campo | Tipo | Obbl. | Note |\n|---|---|---|---|")
        for f in e["fields"].values():
            typ = f"enum {f['enum']}" if f["type"] == "enum" else (f"ref {f['to']}{'[]' if f['many'] else ''}" if f["type"] == "ref" else f["type"])
            notes = ", ".join(x for x in [
                "unico" if f["unique"] else "", "sola lettura" if f["readonly"] else "",
                f"default {f['default']}" if f["default"] is not None else ""] if x)
            L.append(f"| `{f['key']}` {f['label'][loc]} | {typ} | {'sì' if f['required'] else ''} | {notes} |")
        L.append("")
        L.append("Permessi: " + "; ".join(f"**{a}** {', '.join(p)}" for a, p in e["permissions"].items()) + "\n")
        if e["workflow"]:
            wf = e["workflow"]
            L.append("```mermaid\nstateDiagram-v2")
            for k, s in wf["states"].items():
                L.append(f"  {k}: {s['label'][loc]}")
                if s["kind"] == "initial":
                    L.append(f"  [*] --> {k}")
                if s["kind"] == "final":
                    L.append(f"  {k} --> [*]")
            for k, t in wf["transitions"].items():
                for frm in t["from"]:
                    trig = " (auto)" if t["trigger"]["kind"] == "timed" else ""
                    L.append(f"  {frm} --> {t['to']}: {t['label'][loc]}{trig}")
            L.append("```\n")
            L.append("| Transizione | Da → A | Chi | Requisiti |\n|---|---|---|---|")
            for k, t in wf["transitions"].items():
                who = "sistema: " + f"{t['trigger']['at']} {t['trigger'].get('offset') or ''}" if t["trigger"]["kind"] == "timed" else ", ".join(t["by"])
                req = "; ".join(f"{c['field']} {c['op']} {c.get('value', '')}".strip() for c in t["guard"])
                cond = "; ".join(f"{c['field']} {c['op']} {c.get('value', '')}".strip() for c in t["condition"])
                L.append(f"| `{k}` {t['label'][loc]} | {', '.join(t['from'])} → {t['to']} | {who} | {req}{(' [se ' + cond + ']') if cond else ''} |")
            L.append("")
    L.append("## Eventi\n\nOgni evento è scritto nell'outbox nella stessa transazione della modifica e consegnato ai webhook "
             "come CloudEvent firmato (Standard Webhooks). Tipo esterno = prefisso `" + m["app"]["events"]["type_prefix"] + "` + tipo.\n")
    L.append("| Tipo | Categoria | Quando |\n|---|---|---|")
    for t, ev in sorted(M.all_events(m).items()):
        L.append(f"| `{t}` | {ev['category']} | {ev['description']} |")
    L.append("\n## Reazioni\n\n| Nome | Evento | Condizione | Azione |\n|---|---|---|---|")
    for r in m["reactions"]:
        when = ", ".join(f"{k}={v}" for k, v in r["when"].items() if k != "clauses")
        if r["when"].get("clauses"):
            when += (", " if when else "") + "; ".join(f"{c['field']} {c['op']} {c.get('value', '')}" for c in r["when"]["clauses"])
        act = {
            "notify": lambda: f"notifica {', '.join(r['to'])} (template `{r.get('template')}`)",
            "set": lambda: "imposta " + ", ".join(f"{k}={v}" for k, v in (r.get("set") or {}).items()),
            "transition": lambda: f"esegue la transizione `{r.get('transition')}`",
            "schedule": lambda: f"pianifica `{r.get('event')}` a {r.get('at')}",
            "broadcast": lambda: f"broadcast sul canale `{r.get('channel')}`",
            "custom": lambda: f"handler `custom_{r.get('handler')}` (codice scritto a mano)",
        }.get(r.get("do"), lambda: "?")()
        L.append(f"| `{r['name']}` | `{r['on']}` | {when} | {act} |")
    if m["subscriptions"]:
        L.append("\n## Sottoscrittori consigliati\n\n| Nome | URL | Eventi |\n|---|---|---|")
        for s in m["subscriptions"]:
            L.append(f"| {s['name']} | {s.get('url') or '$' + str(s.get('url_env'))} | {', '.join(s['events'])} |")
        L.append("\nSi creano da *Integrazioni* (solo amministratori).")
    return "\n".join(L) + "\n"
