"""TypeScript, i18n and documentation artefacts derived from the model."""

from __future__ import annotations

import json
from typing import Any

from . import model as M

TS_HEADER = "// @generated by appforge from app.yaml. Do not edit: change the model and run /appforge:generate.\n"


def _ts_type(m: dict[str, Any], f: dict[str, Any]) -> str:
    t = f["type"]
    if t == "ref":
        base = "RefValue"
        return f"{base}[]" if f["many"] else f"{base} | null"
    if t == "enum":
        keys = " | ".join(json.dumps(v["key"]) for v in m["enums"][f["enum"]]["values"])
        return f"{{ key: {keys}; labels: Record<string, string> }} | null"
    return {
        "string": "string", "text": "string", "email": "string", "url": "string", "int": "number",
        "number": "number", "money": "number", "bool": "boolean", "date": "string", "datetime": "string",
        "json": "unknown",
    }[t] + ("" if t == "bool" or f["required"] else " | null")


def model_ts(m: dict[str, Any]) -> str:
    """Static metamodel used by the generic UI (src/lib/model.ts)."""
    ents = {}
    for name, e in m["entities"].items():
        fields = []
        for f in sorted(e["fields"].values(), key=lambda x: x["order"]):
            item = {
                "key": f["key"], "type": f["type"], "required": f["required"], "list": f["list"],
                "readonly": f["readonly"], "many": f["many"], "widget": e["ui"]["widgets"][f["key"]],
            }
            if f["type"] == "enum":
                item["enum"] = f["enum"]
            if f["type"] == "ref":
                item["to"] = f["to"]
                item["toTable"] = M.ref_target_table(m, f["to"])
                item["toEntity"] = "user" if f["to"] == "User" else m["entities"][f["to"]]["snake"]
                item["toDisplay"] = "full_name" if f["to"] == "User" else _display_col(m["entities"][f["to"]])
                if f["many"]:
                    item["joinTable"] = f"{e['table']}_{f['key']}"
            for k in ("min", "max", "max_length", "default"):
                if f[k] is not None:
                    item[k if k != "max_length" else "maxLength"] = f[k]
            fields.append(item)
        ent: dict[str, Any] = {
            "name": name, "key": e["snake"], "table": e["table"], "kind": e["kind"], "icon": e["icon"],
            "menu": e["menu"], "order": e["order"], "codePrefix": e["code_prefix"], "display": e["display"],
            "scopeField": e["scope_field"], "fields": fields,
            "create": e["permissions"]["create"],
            "ui": {k: v for k, v in e["ui"].items() if k != "widgets" and v is not None},
        }
        if e["workflow"]:
            ent["workflow"] = {
                "states": [{"key": k, "kind": s["kind"], "color": s["color"], "owner": s["owner"]}
                           for k, s in e["workflow"]["states"].items()],
                "transitions": [{"key": k, "from": t["from"], "to": t["to"], "trigger": t["trigger"]["kind"],
                                 "comment": t["comment"]} for k, t in e["workflow"]["transitions"].items()],
            }
        ents[e["snake"]] = ent
    data = {
        "app": {"name": m["app"]["name"], "slug": m["app"]["slug"], "locales": m["app"]["locales"],
                "scope": (M.scope_entity(m) or {}).get("snake")},
        "roles": {k: {"scoped": r["scoped"]} for k, r in m["roles"].items()},
        "enums": {n: [v["key"] for v in en["values"]] for n, en in m["enums"].items()},
        "entities": dict(sorted(ents.items(), key=lambda kv: kv[1]["order"])),
    }
    body = json.dumps(data, ensure_ascii=False, indent=2)
    return TS_HEADER + f"""import type {{ AppModel }} from "./model-types";

export const MODEL: AppModel = {body};

export const ROLES = {json.dumps(list(m["roles"].keys()))} as const;
export type Role = (typeof ROLES)[number];
"""


def _display_col(e: dict[str, Any]) -> str:
    return e["display"]


def catalog_ts(m: dict[str, Any]) -> str:
    """Event catalogue and payload types for subscribers and the dispatcher."""
    lines = [TS_HEADER, "// Event catalogue: see docs/domain.md for the semantics.\n"]
    lines.append(f"export const CLOUDEVENTS_TYPE_PREFIX = {json.dumps(m['app']['events']['type_prefix'])};\n")
    lines.append(f"export const EVENT_SOURCE = {json.dumps(m['app']['events']['source'])};\n\n")
    lines.append("export type RefValue = { id: string; display: string | null; code?: string; email?: string };\n")
    lines.append("export type Actor = { type: \"user\"; id: string; email: string; name: string | null } | { type: \"system\" };\n")
    lines.append("export type StateValue = { key: string; label?: string; labels: Record<string, string>; kind?: string; color?: string };\n")
    lines.append("export type Recipient = { email: string; locale: string; recipient_type: string; template_key: string };\n\n")
    for name, e in m["entities"].items():
        props = ["  id: string;", "  entity: " + json.dumps(e["snake"]) + ";", "  display: string | null;", "  url: string;"]
        if e["code_prefix"]:
            props.append("  code: string;")
        for f in e["fields"].values():
            props.append(f"  {f['key']}: {_ts_type(m, f)};")
        if e["kind"] == "process":
            props.append("  state: StateValue;")
        props += ["  created_by: Actor;", "  created_at: string;", "  updated_at: string;"]
        lines.append(f"export interface {name}Payload {{\n" + "\n".join(props) + "\n}\n\n")
    lines.append("export type TransitionInfo = { key: string; labels: Record<string, string>; trigger: \"manual\" | \"timed\"; from: StateValue; to: StateValue };\n\n")
    events = M.all_events(m)
    lines.append("export const EVENT_TYPES = {\n")
    for t, ev in sorted(events.items()):
        lines.append(f"  {json.dumps(t)}: {{ category: {json.dumps(ev['category'])}, description: {json.dumps(ev['description'], ensure_ascii=False)} }},\n")
    lines.append("} as const;\nexport type EventType = keyof typeof EVENT_TYPES;\n\n")
    lines.append("/** Shape of `data` for each event type. */\nexport interface EventData {\n")
    for t, ev in sorted(events.items()):
        ent = m["entities"].get(ev.get("entity") or "")
        if not ent:
            if t.startswith("user."):
                lines.append(f"  {json.dumps(t)}: {{ user: {{ id: string; email: string; name: string | null }}; recipients?: Recipient[]; role?: string; scope_id?: string | null }};\n")
            else:
                lines.append(f"  {json.dumps(t)}: Record<string, unknown>;\n")
            continue
        base = f"{{ {ent['snake']}: {ent['name']}Payload; recipients?: Recipient[]"
        suffix = t.split(".", 1)[1]
        if suffix in ("transitioned", "completed") or (ev["category"] == "workflow" and suffix not in ("reminder",)):
            base += "; transition?: TransitionInfo; actor?: Actor; comment?: string | null"
        if suffix == "updated":
            base += "; changed: string[]"
        if suffix == "reminder":
            base += "; reminder: { state: string; after_days: number; count: number }"
        if t in m["events"]:
            base += "; scheduled?: { reaction: string; fire_at: string }"
        lines.append(f"  {json.dumps(t)}: {base} }};\n")
    lines.append("}\n")
    return "".join(lines)


def messages(m: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """The `model` namespace of messages/<locale>.json."""
    out: dict[str, dict[str, Any]] = {}
    for loc in m["app"]["locales"]:
        ns: dict[str, Any] = {"app": {"name": m["app"]["name"], "description": m["app"]["description"]},
                              "roles": {}, "enums": {}, "entities": {}}
        for k, r in m["roles"].items():
            ns["roles"][k] = r["label"][loc]
        for n, en in m["enums"].items():
            ns["enums"][n] = {v["key"]: v["label"][loc] for v in en["values"]}
        for name, e in m["entities"].items():
            ent: dict[str, Any] = {"label": e["label"][loc], "plural": e["plural"][loc],
                                   "fields": {k: f["label"][loc] for k, f in e["fields"].items()}}
            ent["fields"]["code"] = {"it": "Codice"}.get(loc, "Code")
            ent["fields"]["state"] = {"it": "Stato"}.get(loc, "State")
            ent["fields"]["created_by"] = {"it": "Creato da"}.get(loc, "Created by")
            ent["fields"]["created_at"] = {"it": "Creato il"}.get(loc, "Created on")
            if e["workflow"]:
                ent["states"] = {k: s["label"][loc] for k, s in e["workflow"]["states"].items()}
                ent["transitions"] = {k: t["label"][loc] for k, t in e["workflow"]["transitions"].items()}
            ns["entities"][e["snake"]] = ent
        out[loc] = ns
    return out


def merge_messages(existing: dict[str, Any], model_ns: dict[str, Any]) -> dict[str, Any]:
    """Replaces only the `model` namespace, keeping every other key and their order."""
    out = dict(existing)
    out["model"] = model_ns
    return out


